#!/usr/bin/env bash
# OOM Guard: optional earlyoom link. Only needed if you run earlyoom.
# Protecting apps from systemd-oomd (Omarchy's default) needs none of this.
#
# Installs, all owned by root:
#   /usr/lib/oomguard/{rules.py,oomguard-earlyoom-sync}
#   /etc/systemd/system/oomguard-earlyoom-sync.{service,path}
#   /etc/systemd/system/earlyoom.service.d/50-oomguard.conf
# The drop-in appends --ignore <your protected names> to earlyoom's own
# arguments from /etc/default/earlyoom; nothing else about earlyoom changes.
set -euo pipefail
if [[ $EUID != 0 ]]; then
  printf '%s\n' 'Run it with sudo: sudo bash helper/install.sh'
  exit 1
fi
src=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)

if ! systemctl cat earlyoom.service >/dev/null 2>&1; then
  printf '%s\n' 'earlyoom is not installed. Omarchy uses systemd-oomd, which OOM Guard handles without this step.'
  exit 1
fi
execstart=$(systemctl show -p ExecStart --value earlyoom.service)
if [[ $execstart != *'$EARLYOOM_ARGS'* && $execstart != *'EARLYOOM_ARGS'* ]]; then
  printf '%s\n' 'This earlyoom unit does not read $EARLYOOM_ARGS; refusing to guess its command line.'
  exit 1
fi

for dir in /usr/lib/oomguard /etc/oomguard /etc/systemd/system/earlyoom.service.d; do
  [[ ! -L $dir ]] || { printf 'Refusing symlink: %s\n' "$dir"; exit 1; }
  install -d -m 0755 "$dir"
done
install -m 0644 "$src/rules.py" /usr/lib/oomguard/rules.py
install -m 0755 "$src/helper/oomguard-earlyoom-sync" /usr/lib/oomguard/oomguard-earlyoom-sync
install -m 0644 "$src/helper/oomguard-earlyoom-sync.service" /etc/systemd/system/
# The path unit watches each human user's list; generate one PathChanged per home.
{
  printf '%s\n' '# Generated by OOM Guard helper/install.sh. Re-run it after adding a user.'
  printf '%s\n' '[Unit]' 'Description=Watch OOM Guard protected lists for earlyoom' '' '[Path]'
  getent passwd | awk -F: '$3 >= 1000 && $3 < 60000 && $6 ~ /^\/home\// {print $6}' | sort -u | while read -r home; do
    printf 'PathChanged=%s/.config/oomguard/protected.json\n' "$home"
  done
  printf '%s\n' '' '[Install]' 'WantedBy=multi-user.target'
} > /etc/systemd/system/oomguard-earlyoom-sync.path
chmod 0644 /etc/systemd/system/oomguard-earlyoom-sync.path
install -m 0644 "$src/helper/earlyoom-dropin.conf" /etc/systemd/system/earlyoom.service.d/50-oomguard.conf

systemctl daemon-reload
/usr/lib/oomguard/oomguard-earlyoom-sync
systemctl enable --now oomguard-earlyoom-sync.path
systemctl try-restart earlyoom.service
printf '%s\n' 'OOM Guard is linked to earlyoom. Protected apps are now skipped by earlyoom too.'
